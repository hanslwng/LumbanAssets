<?php
/**
 * Re-import an edited RPCPPE .xlsx (round-trip): update quantity_physical_count
 * (and optionally remarks) on property_items matched by property number.
 *
 * POST multipart: file=<xlsx>
 * Optional: update_card_qty=1, update_unit_value=1
 */
error_reporting(0);
ini_set('display_errors', 0);

if (session_status() === PHP_SESSION_NONE) {
    session_start();
}

require_once dirname(__DIR__) . '/bootstrap.php';
require_once dirname(__DIR__) . '/app/helpers/PermissionHelper.php';

header('Content-Type: application/json');

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    jsonResponse(['success' => false, 'message' => 'Method not allowed']);
}

PermissionHelper::require('edit');

$autoload = dirname(__DIR__) . '/vendor/autoload.php';
if (!is_file($autoload)) {
    jsonResponse(['success' => false, 'message' => 'PhpSpreadsheet is not installed']);
}
require_once $autoload;
require_once dirname(__DIR__) . '/includes/rpcppe_workbook.php';

if (!isset($_FILES['file']) || $_FILES['file']['error'] !== UPLOAD_ERR_OK) {
    jsonResponse(['success' => false, 'message' => 'No file uploaded, or upload failed']);
}

$tmp = $_FILES['file']['tmp_name'];
$name = (string) ($_FILES['file']['name'] ?? '');
$ext = strtolower(pathinfo($name, PATHINFO_EXTENSION));
if (!in_array($ext, ['xlsx', 'xlsm'], true)) {
    jsonResponse(['success' => false, 'message' => 'Upload a .xlsx RPCPPE workbook (exported from Print physical count report)']);
}

try {
    $conn = getDBConnection();
} catch (Exception $e) {
    jsonResponse(['success' => false, 'message' => 'Database connection failed']);
}

try {
    $spreadsheet = \PhpOffice\PhpSpreadsheet\IOFactory::load($tmp);
    $parsed = rpcppe_parse_workbook($spreadsheet);
    $spreadsheet->disconnectWorksheets();
    unset($spreadsheet);
} catch (Throwable $e) {
    jsonResponse(['success' => false, 'message' => 'Could not read the Excel file. Export a fresh RPCPPE report, edit it, then re-upload.']);
}

if ($parsed['errors']) {
    jsonResponse([
        'success' => false,
        'message' => 'Validation errors in workbook',
        'errors' => array_slice($parsed['errors'], 0, 20),
    ]);
}

if (!$parsed['updates']) {
    jsonResponse(['success' => false, 'message' => 'No item rows found. Use a workbook generated by Print physical count report.']);
}

$updateCard = !empty($_POST['update_card_qty']);
$updateUv = !empty($_POST['update_unit_value']);

try {
    $conn->beginTransaction();
    $result = rpcppe_apply_updates($conn, $parsed['updates'], $updateCard, $updateUv);
    $conn->commit();
} catch (Throwable $e) {
    if ($conn->inTransaction()) {
        $conn->rollBack();
    }
    jsonResponse(['success' => false, 'message' => 'Failed to apply updates']);
}

$msg = 'Updated ' . $result['updated'] . ' item(s) from RPCPPE workbook.';
if ($result['missing']) {
    $msg .= ' ' . count($result['missing']) . ' property number(s) not found in the system.';
}

if (!function_exists('activityLog')) {
    require_once dirname(__DIR__) . '/includes/audit_log.php';
}
activityLog($conn, 'reports', 'RPCPPE import', [
    'entity_type' => 'physical_count',
    'entity_label' => 'RPCPPE workbook',
    'new_value' => (string) ($result['updated'] ?? 0) . ' updated',
]);

jsonResponse([
    'success' => true,
    'message' => $msg,
    'updated' => $result['updated'],
    'skipped' => $result['skipped'],
    'missing' => array_slice($result['missing'], 0, 30),
]);
